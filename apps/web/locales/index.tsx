function interpolate(message: string, replacements?: Replacements) {
  if (!replacements) return message
  return message.replaceAll(/\{(\w+)\}/g, (placeholder, key: string) =>
    key in replacements ? String(replacements[key]) : placeholder
  )
}

type I18nContextValue = {
  locale: AppLocale
  dateLocale: 'en-US' | 'nl-NL'
  t: (message: string, replacements?: Replacements) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function browserLanguage() {
  if (typeof navigator === 'undefined') return 'en'
  return navigator.languages?.[0] ?? navigator.language
}

export function LocalI18nProvider({ children }: { children: ReactNode }) {
  const local = useLocalBridge()
  const locale = local.settings
    ? resolveInterfaceLocale(local.settings.interfaceLanguage, browserLanguage())
    : localeFromLanguageTag(browserLanguage())

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      dateLocale: locale === 'nl' ? 'nl-NL' : 'en-US',
      t: (message, replacements) =>
        interpolate(locale === 'en' ? (english[message] ?? message) : message, replacements),
    }),
    [locale]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within LocalI18nProvider')
  return context
}
